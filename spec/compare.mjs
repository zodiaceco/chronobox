// Checks every (setup, scenario) against every property with TLC (exhaustive
// up to the model's HORIZON) and writes the comparison table to RESULTS.md.
//   npm ci && npm run compare        (needs Java 17+ on PATH)
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

// Optional: the delay in hours (a multiple of 24), e.g. `node compare.mjs 72`.
const DELAY = Number(process.argv[2] ?? 48);
if (!(DELAY >= 48 && DELAY % 24 === 0)) throw new Error("DELAY must be a multiple of 24 and at least 48");

const SETUPS = { simple: "Simple", guardianVeto: "With guardian", guardianRecovery: "With guardian + recovery" };
const SCENARIOS = [
  ["none", "No incident"],
  ["coercion", "Coercion (forced to sign with H, for less than the delay)"],
  ["hotKeyLeak", "Hot key leaked"],
  ["hotKeyTaken", "Hot key taken (only the attacker has it: long coercion, stolen without a backup, or the owner can never sign again)"],
  ["hotKeyLost", "Hot key lost"],
  ["guardianLeak", "Guardian key leaked (a copy: the guardian still has it)"],
  ["guardianHostile", "Guardian hostile (only they hold the key)"],
  ["guardianLost", "Guardian lost"],
  ["guardianHostileHotLost", "Guardian hostile and hot key lost"],
  ["bothKeys", "Both keys leaked"],
];
const PROPS = [
  ["noTheft", "safe"],
  ["recovers", "recovers"],
  ["withdraws", "can withdraw"],
];

mkdirSync("results", { recursive: true });
const SPEC = DELAY === 48 ? "chronobox.qnt" : "results/chronobox-delay.qnt";
if (DELAY !== 48) writeFileSync(SPEC, readFileSync("chronobox.qnt", "utf8").replace(/pure val DELAY = \d+/, `pure val DELAY = ${DELAY}`));
const results = {};
for (const [scenario] of SCENARIOS) {
  for (const setup of Object.keys(SETUPS)) {
    if (setup === "simple" && ["guardianLeak", "guardianHostile", "guardianLost", "bothKeys", "guardianHostileHotLost"].includes(scenario)) continue;
    for (const [prop] of PROPS) {
      const name = `${setup}_${scenario}_${prop}${DELAY === 48 ? "" : `_${DELAY}h`}`;
      let out = "";
      let ok;
      try {
        out = execFileSync("npx", ["quint", "verify", SPEC, "--backend=tlc", `--init=init_${setup}_${scenario}`, "--step=step", `--invariant=${prop}`], { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
        ok = /No violation found/.test(out);
      } catch (e) {
        out = String(e.stdout ?? "") + String(e.stderr ?? "");
        ok = false;
      }
      if (!ok && !/Invariant .* violated|violation/i.test(out)) throw new Error(`${name}: checker failed\n${out}`);
      writeFileSync(`results/${name}.txt`, out);
      results[`${setup}_${scenario}_${prop}`] = ok;
      process.stdout.write(`${ok ? "holds   " : "VIOLATED"}  ${name}\n`);
    }
  }
}

const cell = (setup, scenario) => {
  if (!(`${setup}_${scenario}_noTheft` in results)) return "n/a";
  return PROPS.map(([p, label]) => `${results[`${setup}_${scenario}_${p}`] ? "✅" : "❌"} ${label}`).join("<br>");
};
const lines = [
  `# Comparison, delay ${DELAY} h (generated by \`npm run compare\`)`,
  "",
  "✅ = holds in every reachable state; ❌ = TLC found a counterexample (trace in `results/`).",
  "",
  `| Scenario | ${Object.values(SETUPS).join(" | ")} |`,
  `|---|${Object.keys(SETUPS).map(() => "---").join("|")}|`,
  ...SCENARIOS.map(([sc, label]) => `| ${label} | ${Object.keys(SETUPS).map((st) => cell(st, sc)).join(" | ")} |`),
  "",
];
writeFileSync(DELAY === 48 ? "RESULTS.md" : `RESULTS-${DELAY}h.md`, lines.join("\n"));
console.log("\n" + lines.join("\n"));
